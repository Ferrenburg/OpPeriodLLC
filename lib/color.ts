// WCAG contrast math, used to pick readable text on project accent colors.

function luminance(hex: string): number {
  const channels = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

// White or ink, whichever reads better on the given background.
export function readableOn(background: string, light = "#FFFFFF", dark = "#0E1010"): string {
  return contrast(background, light) >= contrast(background, dark) ? light : dark;
}
